#!/usr/bin/env python3
"""Turn the chair tint template (art/sets/slat_template.png) into the Lua data file the script
reads: DFHack's Lua cannot read the pixels of a PNG.

The PNG is 4 rows (wood, stone, metal, glass) of 4 facings (N, E, S, W), 32x32 each.  The Lua
file returns 16 strings, row by row; each is one tile as 1024 pixels of 8 hex digits, RRGGBBAA.

Usage: make_template.py            write scripts/internal/improved-chairs/template.lua
       make_template.py --check    fail if that file does not match the PNG
"""
import pathlib
import sys

from PIL import Image

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE / "sets" / "slat_template.png"
OUT = HERE.parent / "scripts" / "internal" / "improved-chairs" / "template.lua"
TILE, ROWS, FACINGS = 32, 4, 4


def render():
    im = Image.open(SRC).convert("RGBA")
    if im.width < TILE * FACINGS or im.height < TILE * ROWS:
        sys.exit(f"{SRC} is {im.width}x{im.height}, need {TILE * FACINGS}x{TILE * ROWS}")
    lines = [
        "-- Generated by art/make_template.py from art/sets/slat_template.png; do not edit.",
        "-- 16 tiles: rows wood, stone, metal, glass; in each, facings N, E, S, W.",
        "-- A tile is 32x32 pixels, 8 hex digits each: RRGGBBAA.",
        "return {",
    ]
    for row in range(ROWS):
        for facing in range(FACINGS):
            tile = im.crop((facing * TILE, row * TILE, (facing + 1) * TILE, (row + 1) * TILE))
            lines.append('"' + tile.tobytes().hex() + '",')
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = render()
    if sys.argv[1:] == ["--check"]:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT} does not match {SRC}; run art/make_template.py")
        print(f"{OUT} matches {SRC}")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT}")
